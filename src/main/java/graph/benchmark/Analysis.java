package graph.benchmark;

import graph.metrics.Stats;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeSet;
import java.util.function.ToDoubleFunction;

/**
 * Turns the measured rows into the numbers used in the report: every counter divided by its
 * complexity formula (a constant ratio confirms the complexity class), least-squares slopes on
 * log-log axes, and the median times. Written to {@code results/analysis.md} so that one command
 * reproduces every number of the report.
 */
public final class Analysis {

    /** Algorithm names in the order used everywhere (CSV, tables, plots). */
    public static final List<String> ALGORITHMS = List.of("Kruskal", "Prim", "Kosaraju", "Kahn", "DagShortestPath");
    /** Densities in table order. */
    public static final List<String> DENSITIES = List.of("sparse", "dense");

    private record Ratio(String algorithm, String formula, ToDoubleFunction<ResultRow> value) {
    }

    private static double log2(double x) {
        return Math.log(x) / Math.log(2);
    }

    private static final List<Ratio> RATIOS = List.of(
            new Ratio("Kruskal", "edgeScans / E", r -> (double) r.edgeScans() / r.m()),
            new Ratio("Kruskal", "dsuOps / E", r -> (double) r.dsuOps() / r.m()),
            new Ratio("Kruskal", "comparisons / (E log2 E)", r -> r.comparisons() / (r.m() * log2(r.m()))),
            new Ratio("Prim", "edgeScans / 2E", r -> r.edgeScans() / (2.0 * r.m())),
            new Ratio("Prim", "comparisons / (E log2 V)", r -> r.comparisons() / (r.m() * log2(r.n()))),
            new Ratio("Kosaraju", "edgeScans / (V + E)", r -> (double) r.edgeScans() / (r.n() + r.m())),
            new Ratio("Kosaraju", "edgeScans / 2E", r -> r.edgeScans() / (2.0 * r.m())),
            new Ratio("Kahn", "edgeScans / (V + E)", r -> (double) r.edgeScans() / (r.n() + r.m())),
            new Ratio("Kahn", "edgeScans / E", r -> (double) r.edgeScans() / r.m()),
            new Ratio("DagShortestPath", "edgeScans / (V + E)", r -> (double) r.edgeScans() / (r.n() + r.m())),
            new Ratio("DagShortestPath", "comparisons / E", r -> (double) r.comparisons() / r.m()));

    private Analysis() {
    }

    /** Total counted work of a row: dsuOps + edgeScans + comparisons. */
    public static long totalOperations(ResultRow r) {
        return r.dsuOps() + r.edgeScans() + r.comparisons();
    }

    /** Rows of one algorithm and density, ordered by n. */
    public static List<ResultRow> select(List<ResultRow> rows, String algorithm, String density) {
        List<ResultRow> out = new ArrayList<>();
        for (ResultRow r : rows) {
            if (r.algorithm().equals(algorithm) && r.density().equals(density)) {
                out.add(r);
            }
        }
        out.sort((a, b) -> Integer.compare(a.n(), b.n()));
        return out;
    }

    /** Log-log slope of {@code metric} against n, or NaN if fewer than two positive points. */
    public static double slope(List<ResultRow> series, ToDoubleFunction<ResultRow> metric) {
        double[] x = new double[series.size()];
        double[] y = new double[series.size()];
        for (int i = 0; i < series.size(); i++) {
            x[i] = series.get(i).n();
            y[i] = metric.applyAsDouble(series.get(i));
            if (!(y[i] > 0)) {
                return Double.NaN;
            }
        }
        return series.size() < 2 ? Double.NaN : Stats.logLogSlope(x, y);
    }

    /** Writes {@code analysis.md}. */
    public static void write(Path file, List<ResultRow> rows, Map<String, Long> dsuPointerHops,
                             List<BenchmarkRunner.ReferenceCheck> referenceChecks) throws IOException {
        List<Integer> sizes = new ArrayList<>(new TreeSet<>(rows.stream().map(ResultRow::n).toList()));
        StringBuilder sb = new StringBuilder();
        sb.append("# Benchmark analysis (generated by BenchmarkRunner - do not edit)\n\n");
        sb.append("All counters are counted inside the algorithms; with `new Random(42)` they are identical on every "
                + "machine. Times are medians of the timed runs and depend on the machine.\n\n");

        sb.append("## 1. Counters divided by the complexity formula\n\n");
        sb.append("A ratio that stays constant as n grows confirms the complexity class.\n\n");
        header(sb, "algorithm | density | ratio", sizes);
        for (Ratio ratio : RATIOS) {
            for (String density : DENSITIES) {
                List<ResultRow> series = select(rows, ratio.algorithm(), density);
                if (series.isEmpty()) {
                    continue;
                }
                sb.append("| ").append(ratio.algorithm()).append(" | ").append(density).append(" | ")
                        .append(ratio.formula()).append(" |");
                for (int n : sizes) {
                    ResultRow r = find(series, n);
                    sb.append(' ').append(r == null ? "" : fmt(ratio.value().applyAsDouble(r), 3)).append(" |");
                }
                sb.append('\n');
            }
        }
        sb.append('\n');

        sb.append("### DSU: parent links followed per find (Kruskal)\n\n");
        sb.append("Union by rank + path compression: the average path length stays almost constant "
                + "(the alpha(n) behaviour).\n\n");
        header(sb, "density | finds and hops", sizes);
        for (String density : DENSITIES) {
            List<ResultRow> series = select(rows, "Kruskal", density);
            if (series.isEmpty()) {
                continue;
            }
            sb.append("| ").append(density).append(" | hops / find |");
            for (int n : sizes) {
                ResultRow r = find(series, n);
                Long hops = r == null ? null : dsuPointerHops.get(r.graph());
                if (r == null || hops == null) {
                    sb.append(" |");
                    continue;
                }
                long finds = r.dsuOps() - (r.n() - 1L);   // dsuOps = finds + (n-1) successful unions
                sb.append(' ').append(fmt((double) hops / finds, 3)).append(" |");
            }
            sb.append('\n');
        }
        sb.append('\n');

        sb.append("## 2. Log-log slopes against n (least squares over all sizes)\n\n");
        sb.append("Slope 1.00 = linear work. `total ops` = dsuOps + edgeScans + comparisons.\n\n");
        sb.append("| algorithm | density | edgeScans | comparisons | dsuOps | total ops | time |\n");
        sb.append("|---|---|---|---|---|---|---|\n");
        for (String algorithm : ALGORITHMS) {
            for (String density : DENSITIES) {
                List<ResultRow> s = select(rows, algorithm, density);
                if (s.size() < 2) {
                    continue;
                }
                sb.append("| ").append(algorithm).append(" | ").append(density).append(" | ")
                        .append(fmtSlope(slope(s, ResultRow::edgeScans))).append(" | ")
                        .append(fmtSlope(slope(s, ResultRow::comparisons))).append(" | ")
                        .append(fmtSlope(slope(s, ResultRow::dsuOps))).append(" | ")
                        .append(fmtSlope(slope(s, r -> totalOperations(r)))).append(" | ")
                        .append(fmtSlope(slope(s, ResultRow::timeMs))).append(" |\n");
            }
        }
        sb.append('\n');

        sb.append("## 3. Median wall-clock time (ms)\n\n");
        header(sb, "algorithm | density", sizes);
        for (String algorithm : ALGORITHMS) {
            for (String density : DENSITIES) {
                List<ResultRow> s = select(rows, algorithm, density);
                if (s.isEmpty()) {
                    continue;
                }
                sb.append("| ").append(algorithm).append(" | ").append(density).append(" |");
                for (int n : sizes) {
                    ResultRow r = find(s, n);
                    sb.append(' ').append(r == null ? "" : fmt(r.timeMs(), 3)).append(" |");
                }
                sb.append('\n');
            }
        }
        sb.append('\n');

        sb.append("## 4. Reference values (computed vs assignment table)\n\n");
        sb.append("| n | m | quantity | computed | expected | status |\n|---|---|---|---|---|---|\n");
        for (BenchmarkRunner.ReferenceCheck c : referenceChecks) {
            sb.append(String.format(Locale.ROOT, "| %d | %d | %s | %d | %d | %s |%n", c.n(), c.m(), c.quantity(),
                    c.computed(), c.expected(), c.ok() ? "OK" : "MISMATCH"));
        }
        if (file.getParent() != null) {
            Files.createDirectories(file.getParent());
        }
        Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
    }

    private static void header(StringBuilder sb, String first, List<Integer> sizes) {
        sb.append("| ").append(first).append(" |");
        for (int n : sizes) {
            sb.append(" n=").append(n).append(" |");
        }
        sb.append('\n').append("|---".repeat(first.split("\\|").length));
        sb.append("|---:".repeat(sizes.size())).append("|\n");
    }

    private static ResultRow find(List<ResultRow> series, int n) {
        for (ResultRow r : series) {
            if (r.n() == n) {
                return r;
            }
        }
        return null;
    }

    private static String fmt(double v, int digits) {
        return String.format(Locale.ROOT, "%." + digits + "f", v);
    }

    private static String fmtSlope(double v) {
        return Double.isNaN(v) ? "-" : fmt(v, 3);
    }
}
